// 분석 페이지의 "기간별 상태 변화" 추이 차트 전용 예시 데이터.
//
// drains 스냅샷 하나로는 시간 흐름을 재구성할 수 없고, 백엔드는 아직 detections를
// 일자별로 집계하는 엔드포인트가 없다(detections 자체는 append-only 로그라 원본은
// 남아있지만, 집계 API가 없어 프런트에서 대량 조회하는 건 비용이 크다). forecast.py의
// KMA 실패 시 더미 날씨, infer.py의 가중치 없을 때 더미 판정과 같은 성격의
// "하드웨어/데이터 준비 전 폴백" 패턴을 여기서도 그대로 따른다 — 백엔드에
// 일자별 집계 엔드포인트가 추가되면 이 파일을 그 응답으로 교체한다.
//
// 그 외 분석 페이지의 모든 수치(상태 구성, 우선순위 원인 기여도, 노선/차량별 비교,
// TOP 10, 조치 성과, 데이터 품질)는 현재 drains/vehicles/system-events 스냅샷에서
// 실시간으로 계산되며 이 파일을 쓰지 않는다.
function points(dates, occ, prevOcc, clear, occluded, blocked, unassessable, inspected, coverage) {
  return dates.map((date, i) => ({
    date,
    occ: occ[i],
    prevOcc: prevOcc[i],
    clear: clear[i],
    occluded: occluded[i],
    blocked: blocked[i],
    unassessable: unassessable[i],
    inspected: inspected[i],
    coverage: coverage[i],
  }))
}

